import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const base = process.env.SMOKE_URL || 'http://127.0.0.1:4178/docs/';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox', '--enable-webgl', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
await mkdir('/tmp/crashout-qa', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
  const errors = [], failures = [], tiles = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.url().includes('tiles.maps.eox.at') && r.status() === 200) tiles.push(r.url()); if (r.url().startsWith(base) && r.status() >= 400) failures.push(`${r.status()} ${r.url()}`); });
  await page.goto(base, { waitUntil: 'networkidle', timeout: 60000 });
  await page.waitForFunction(() => window.__crashout?.ready, { timeout: 15000 });
  await page.waitForFunction(() => window.__crashout.buildingCount > 1000 && window.__crashout.buildingsReady, { timeout: 30000 });
  await page.waitForTimeout(2000);
  assert.equal(await page.locator('#render-status').isVisible(), false, await page.locator('#render-status').textContent());
  assert.equal(await page.locator('#satellite').isChecked(), true);
  assert.equal(await page.locator('#altitude').textContent(), '35,050');
  assert.equal(await page.locator('#profile').inputValue(), 'recorded');
  assert.equal(await page.locator('#radio').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('#sound').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.evaluate(() => window.__crashout.radioPaused), true);
  assert.equal(await page.locator('#telemetry-panel').getAttribute('open'), '');
  await page.locator('#telemetry-panel summary').focus();
  await page.keyboard.press('Space');
  assert.equal(await page.locator('#altitude').isVisible(), false);
  assert.equal(await page.evaluate(() => window.__crashout.playing), false);
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#altitude').isVisible(), true);
  assert.ok(tiles.length > 0, 'satellite tiles should load in the real browser');
  await page.screenshot({ path: '/tmp/crashout-qa/cockpit-desktop.png' });
  const cameraBeforeDrag = await page.evaluate(() => ({ pitch: window.__crashout.cameraPitch, heading: window.__crashout.cameraHeading, frames: window.__crashout.renderedFrames }));
  await page.mouse.move(650, 300);
  await page.mouse.down();
  await page.mouse.move(880, 420, { steps: 8 });
  await page.mouse.up();
  assert.equal(await page.evaluate(() => window.getSelection().toString()), '', 'dragging the locked cockpit must not select interface text');
  await page.waitForFunction(frames => window.__crashout.renderedFrames > frames + 1, cameraBeforeDrag.frames);
  const cameraAfterDrag = await page.evaluate(() => ({ pitch: window.__crashout.cameraPitch, heading: window.__crashout.cameraHeading }));
  assert.ok(Math.abs(cameraAfterDrag.pitch - cameraBeforeDrag.pitch) < 1e-9, 'dragging must not change cockpit pitch');
  assert.ok(Math.abs(cameraAfterDrag.heading - cameraBeforeDrag.heading) < 1e-9, 'dragging must not change cockpit heading');
  await page.locator('#play').click();
  await page.waitForTimeout(500);
  assert.ok((await page.evaluate(() => window.__crashout.sample.time)) > 0);
  await page.waitForFunction(() => window.__crashout.soundEnabled && window.__crashout.soundState === 'running');
  await page.locator('#play').click();
  await page.locator('#profile').selectOption('custom');
  await page.waitForFunction(() => window.__crashout.profile === 'custom');
  await page.locator('#timeline').evaluate(e => { e.value = '.75'; e.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.waitForFunction(() => window.__crashout.sample.progress >= .749);
  assert.ok((await page.evaluate(() => window.__crashout.cameraPitch)) < cameraBeforeDrag.pitch - .4, 'camera must still follow the aircraft descent');
  await page.screenshot({ path: '/tmp/crashout-qa/descent.png' });
  await page.locator('#timeline').evaluate(e => { e.value = '1'; e.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.waitForFunction(() => window.__crashout.sample.finished);
  assert.equal((await page.evaluate(() => window.__crashout.sample.speedMph)), 800);
  assert.equal(await page.locator('#impact-card').isVisible(), true);
  await page.locator('#reset').click();
  await page.locator('#profile').selectOption('recorded');
  await page.waitForFunction(() => window.__crashout?.profile === 'recorded');
  assert.equal(await page.locator('#altitude').textContent(), '35,050');
  await page.locator('#timeline').evaluate(e => { e.value = '.95'; e.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.waitForFunction(() => window.__crashout.sample.inferred);
  assert.equal(await page.locator('#mode-label').textContent(), 'INFERRED FINAL DESCENT');
  await page.waitForFunction(() => window.__crashout.radioEnabled && Math.abs(window.__crashout.radioTime - window.__crashout.radioTarget) < .15);
  await page.locator('#rate').selectOption('2');
  await page.locator('#play').click();
  await page.waitForFunction(() => !window.__crashout.radioPaused && window.__crashout.radioRate === 2);
  await page.locator('#play').click();
  await page.locator('#timeline').evaluate(e => { e.value = '.997'; e.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.waitForFunction(() => window.__crashout.sample.progress >= .9969);
  const frameBeforeCloseup = await page.evaluate(() => window.__crashout.renderedFrames);
  await page.waitForFunction(frames => window.__crashout.renderedFrames > frames + 2, frameBeforeCloseup);
  await page.screenshot({ path: '/tmp/crashout-qa/buildings-closeup.png' });
  await page.locator('#timeline').evaluate(e => { e.value = '1'; e.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.waitForFunction(() => window.__crashout.sample.finished);
  assert.equal(await page.locator('#altitude').textContent(), '16');
  assert.equal(await page.locator('#impact-card h2').textContent(), 'Ground impact');
  await page.waitForFunction(() => Math.abs(window.__crashout.radioTime - 105.65) < .15 && window.__crashout.radioPaused);
  await page.locator('#radio').click();
  await page.locator('#rate').selectOption('1');
  await page.locator('#reset').click();
  await page.locator('#view-mode').click();
  await page.waitForTimeout(300);
  assert.equal(await page.locator('#instrument-panel').isVisible(), false);
  await page.screenshot({ path: '/tmp/crashout-qa/overview.png' });
  await page.locator('#view-mode').click();
  await page.locator('#profile').selectOption('custom');
  await page.locator('#weather').uncheck();
  await page.locator('#motion').uncheck();
  await page.locator('#buildings').uncheck();
  await page.waitForFunction(() => !window.__crashout.buildingsVisible);
  await page.locator('#buildings').check();
  await page.locator('#satellite').uncheck();
  await page.waitForFunction(() => !window.__crashout.satellite);
  assert.equal(await page.evaluate(() => window.__crashout.satellite), false);
  await page.locator('#satellite').check();
  await page.locator('#weather').check();
  await page.locator('#sources-button').click();
  assert.equal(await page.locator('#sources-dialog').isVisible(), true);
  assert.equal(await page.locator('#source-list a[href*="2117115827682234691"]').count(), 1);
  assert.equal(await page.locator('#source-list a[href="./data/buildings.json"]').count(), 1);
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(500);
  assert.equal(await page.locator('#altitude').isVisible(), false);
  assert.equal(await page.locator('#satellite').isVisible(), false);
  assert.equal(await page.locator('#telemetry-panel summary').isVisible(), true);
  assert.equal(await page.locator('#environment-panel summary').isVisible(), true);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: '/tmp/crashout-qa/cockpit-mobile.png' });
  await page.locator('#telemetry-panel summary').click();
  assert.equal(await page.locator('#altitude').isVisible(), true);
  assert.equal(await page.locator('#satellite').isVisible(), false);
  await page.locator('#telemetry-panel summary').click();
  await page.locator('#environment-panel summary').click();
  assert.equal(await page.locator('#satellite').isVisible(), true);
  await page.locator('#weather').uncheck();
  await page.locator('#environment-panel summary').click();
  await page.locator('#environment-panel summary').click();
  assert.equal(await page.locator('#weather').isChecked(), false);
  await page.locator('#weather').check();
  await page.locator('#environment-panel summary').click();
  await page.locator('#play').click(); await page.waitForTimeout(200); await page.locator('#play').click();
  assert.deepEqual(errors, []); assert.deepEqual(failures, []);
  console.log(JSON.stringify({ result: 'PASS', base, satelliteTilesLoaded: tiles.length, desktop: '1440x1000', mobile: '390x844', checks: 'WebGL, assets, satellite, playback, scrubbing, impact, recorded track boundary, overview, toggles, evidence, mobile layout', screenshots: '/tmp/crashout-qa' }, null, 2));
} finally { await browser.close(); }
